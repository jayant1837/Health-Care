    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        // TODO add your handling code here:
        int phone;
        name=(String)tf1.getText();
        nikename=tf2.getText();
        email=tf4.getText();
        pass=(String)tf5.getText();
        repass=tf6.getText();
        fullname=tf7.getText();
        boolean valid=true,v=true;
        int count=0,unmatch=0,nknmatch=0,pmatch=0,emailmatch=0;
        if(name.equals(""))
        {
            v=false;
            JOptionPane.showMessageDialog(null,"enter your username");
        }
        if(nikename.equals(""))
        {
            v=false;
            JOptionPane.showMessageDialog(null,"enter your nikename");
        }
        if(tf3.getText().equals(""))
        {
            v=false;
            JOptionPane.showMessageDialog(null,"enter your phone");
        }
        if(email.equals(""))
        {
            v=false;
            JOptionPane.showMessageDialog(null,"enter your emali");
        }
        if(pass.equals(""))
        {
            v=false;
            JOptionPane.showMessageDialog(null,"enter your password");
        }
        if(repass.equals(""))
        {
            v=false;
            JOptionPane.showMessageDialog(null,"enter your re-passwaord");
        }
        if(fullname.equals(""))
        {
            v=false;
            JOptionPane.showMessageDialog(null,"enter your Full name");
        }
        if(v==true)
        {
            try
            {
                q="select * from account;";
                rs=st.executeQuery(q);
                while(rs.next())
                {
                    if(name.compareTo(rs.getString("username"))==0)
                    {
                        unmatch=1;
                    }
                    if(nikename.compareTo(rs.getString("nikname"))==0)
                    {
                        nknmatch=1;
                    }
                    if(tf3.getText().equals(rs.getString("phone_no")))
                    {
                        pmatch=1;
                    }
                    if(email.equals(rs.getString("email")))
                    {
                        emailmatch=1;
                    }
                }
            }
            catch(Exception e)
            {
                JOptionPane.showMessageDialog(null,"error in create account");
            }
            if(unmatch==1)
            {
                valid=false;
                JOptionPane.showMessageDialog(null,"Username is already create");
            }
            if(nknmatch==1)
            {
                valid=false;
                JOptionPane.showMessageDialog(null,"nikename is already create");
            }
            if(pmatch==1)
            {
                valid=false;
                JOptionPane.showMessageDialog(null,"phone is already used");
            }
            if(tf3.getText().length()<10)
            {
                valid=false;
                JOptionPane.showMessageDialog(null,"phone is less than 10 digit");
            }
            if(tf3.getText().length()>11)
            {
                valid=false;
                JOptionPane.showMessageDialog(null,"phone is grether than 11 digit");
            }
            if(emailmatch==1)
            {
                valid=false;
                JOptionPane.showMessageDialog(null,"email is already used");
            }
            if(pass.trim().length()<7)
            {
                valid=false;
                JOptionPane.showMessageDialog(null,"password should Greather then 8 digit");
            }
            int a=pass.indexOf(" ");
            if(a>=0)
            {
                valid=false;
                JOptionPane.showMessageDialog(null,"password is invalid as space is not allowed in it");
            }
            char x=pass.charAt(0);
            if(!(x>='A' && x<='Z'))
            {
                valid=false;
                JOptionPane.showMessageDialog(null,"The password is invalid because the first character must be a letter, and all letters must be uppercase");
            }
            char z[]=pass.toCharArray();
            int n=0;
            for(int i=0;i<z.length;i++)
            {
                if(z[i]=='@' || z[i]=='#' || z[i]=='!' || z[i]=='$' || z[i]=='%' || z[i]=='^' || z[i]=='&' || z[i]=='*' || z[i]=='(' || z[i]==')' || z[i]=='-' || z[i]=='_' || z[i]=='+' || z[i]=='=' || z[i]=='{' || z[i]=='}' || z[i]=='[' || z[i]==']' || z[i]==':' || z[i]==';' || z[i]=='"' || z[i]=='\'' || z[i]=='<' || z[i]=='>' || z[i]==',' || z[i]=='.' || z[i]=='?' || z[i]=='/' || z[i]=='\\' || z[i]=='|' || z[i]=='~' || z[i]=='`')
                {
                    n=1;
                }
            }
            if(n==0)
            {
                JOptionPane.showMessageDialog(null,"Enter at leat one Specail Symbol");
            }
            if(pass.compareTo(repass)==1)
            {
                valid=false;
                JOptionPane.showMessageDialog(null,"password does not match");
            }
            try
            {
                if(valid==true && n==1)
                {
                    q="insert into account values('"+name+"','"+nikename+"','"+tf3.getText()+"','"+email+"','"+pass+"','"+fullname+"');";
                    st.executeUpdate(q);
                    tf1.setText("");
                        tf2.setText("");
                        tf3.setText("");
                        tf4.setText("");
                        tf5.setText("");
                        tf6.setText("");
                        tf7.setText("");
                    count=1;
                }
            }
            catch(Exception e)
            {
                JOptionPane.showMessageDialog(null,"error in create account");
            }
            if(count==1)
            {
                JOptionPane.showMessageDialog(null,"Account Create");
            }
        }
    }//GEN-LAST:event_jButton1ActionPerformed

