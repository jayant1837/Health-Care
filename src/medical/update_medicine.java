    private void jButton5ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton5ActionPerformed
        // TODO add your handling code here:
        md_id=Long.parseLong(tf1.getText());
        mdname=tf2.getText();
        purchases_price =Long.parseLong(tf5.getText());
        sales_price =Long.parseLong(tf7.getText());
        expiry_date=tf8.getText();
        quantity=Long.parseLong(tf4.getText());
        int count=0;
        purchase_date=tf3.getText();
        boolean valid=true;
        if(tf2.getText().equals(""))
        {
            JOptionPane.showMessageDialog(null,"enter Medicine name");
            valid=false;
        }
        if(tf4.getText().equals(""))
        {
            JOptionPane.showMessageDialog(null,"enter Quantity");
            valid=false;
        }
        if(tf5.getText().equals(""))
        {
            JOptionPane.showMessageDialog(null,"enter Purchase price");
            valid=false;
        }
        if(tf7.getText().equals(""))
        {
            JOptionPane.showMessageDialog(null,"enter Sales price");
            valid=false;
        }
        if(tf8.getText().equals(""))
        {
            JOptionPane.showMessageDialog(null,"enter Expiry date");
            valid=false;
        }
        if(valid==true)
        {
            try
            {
                q="select count(md_id) from medical_record where expiry_date<curdate() and md_id="+Integer.parseInt(tf1.getText())+";";
                rs=st.executeQuery(q);
                int check=0;
                while(rs.next())
                {
                    check=rs.getInt("count(md_id)");
                }
                if(check==1)
                {
                    JOptionPane.showMessageDialog(this,"this medicine was expiry");
                }
                if(check==0)
                {
                    int new_stock=0;
                    int old_stock=0;
                    int total_stock=0;
                    q="select stock from medical_record where md_id="+Integer.parseInt(tf1.getText())+";";
                    rs=st.executeQuery(q);
                    while(rs.next())
                    {
                        old_stock=rs.getInt("stock");
                    }
                    new_stock=Integer.parseInt(tf4.getText());
                    total_stock=new_stock-old_stock;
                    q="update medical_record set stock="+quantity+" where md_id="+md_id+";";
                    st.executeUpdate(q);
                    q="insert into purchase_report values("+md_id+",'"+mdname+"','"+purchase_date+"',"+quantity+");";
                    st.executeUpdate(q);
                    JOptionPane.showMessageDialog(null,"data update");
                    tf1.setText("");
                    tf2.setText("");
                    tf3.setText("");
                    tf4.setText("");
                    tf5.setText("");
                    tf7.setText("");
                    tf8.setText("");
                }
            }
            catch(Exception e)
            {
                JOptionPane.showMessageDialog(null,"error in save connection");
            }
        }
    }//GEN-LAST:event_jButton5ActionPerformed

