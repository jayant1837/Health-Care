    private void tf1KeyPressed(java.awt.event.KeyEvent evt) {//GEN-FIRST:event_tf1KeyPressed
        // TODO add your handling code here:
        if(evt.getKeyCode()==10)
        {
            Long id=Long.parseLong(tf1.getText());
            try
            {
                Class.forName("java.sql.Driver");
                con=DriverManager.getConnection("jdbc:mysql://localhost:3306/health_care", "root", "");
                st=con.createStatement();
                q="select * from medical_record where md_id="+id+";";
                rs=st.executeQuery(q);
                while(rs.next())
                {
                    tf2.setText(rs.getString("md_name"));
                    tf3.setText(rs.getString("purchase_date"));
                    tf8.setText(rs.getString("expiry_date"));
                    tf4.setText(""+rs.getLong("stock"));
                    tf5.setText(""+rs.getInt("purchase_price"));
                    tf7.setText(""+rs.getLong("sales_price"));
                }
            }
            catch(Exception e)
            {
                JOptionPane.showMessageDialog(this,"error in search connection");
            }
        }
    }//GEN-LAST:event_tf1KeyPressed

